"""Content hashes of the figures, props and textures for the scene's asset URLs.

    python -m game.tools.asset_versions --write   # regenerate game/frontend/asset-versions.js
    python -m game.tools.asset_versions --check   # fail when it is stale

The scene loads ``models/<key>.glb?v=<hash>`` (and the same for props and
textures), so a changed file gets a new URL. After ``--write``, rebuild the
bundle (``cd game/frontend && npm run build``); ``make_ff_release.py --check``
fails when the module or the bundle is stale.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

from game.assets import MODEL_FILES, PROP_FILES, STATIC, TEXTURE_FILES

MODULE = Path(__file__).resolve().parents[1] / 'frontend' / 'asset-versions.js'
_HEADER_RE_PREFIX = '// Generated by '


def versions(static=STATIC):
    out = {}
    for name in MODEL_FILES + PROP_FILES + TEXTURE_FILES:
        path = static / name
        if path.is_file():
            out[name] = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
    return out


def render(static=STATIC):
    table = json.dumps(versions(static), indent=2, sort_keys=True).replace('"', "'")
    return f"""// Generated by game/tools/asset_versions.py; do not edit by hand.
// Content hashes of the figures, props and textures: a changed file gets a new URL,
// because browsers cache static files across sessions.
export const ASSET_VERSIONS = Object.freeze({table});

export function versioned(path) {{
  const version = ASSET_VERSIONS[path];
  return version ? `${{path}}?v=${{version}}` : path;
}}
"""


def _strip_comments(js_text):
    return '\n'.join(ln for ln in js_text.splitlines() if not ln.lstrip().startswith('//')).strip()


def stale(static=STATIC):
    if not MODULE.is_file():
        return True
    return _strip_comments(MODULE.read_text(encoding='utf-8')) != _strip_comments(render(static))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    if args.write:
        MODULE.write_text(render(), encoding='utf-8')
        print(f'wrote {MODULE.relative_to(Path.cwd()) if MODULE.is_relative_to(Path.cwd()) else MODULE}')
        return 0
    if stale():
        print('asset-versions.js is stale: run python -m game.tools.asset_versions --write and rebuild')
        return 1
    print('asset versions are current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
